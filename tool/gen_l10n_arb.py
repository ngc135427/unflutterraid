def write_arb(path: Path, data: dict[str, str]) -> None:
    out: dict = {}
    for key, value in data.items():
        out[key] = value
        if key in meta:
            out[f"@{key}"] = meta[key]
    path.write_text(
        json.dumps(out, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    keys = [k for k in data if not k.startswith("@")]
    print(f"{path.relative_to(ROOT)}: {len(keys)} keys")


def main() -> None:
    if set(zh) != set(en):
        missing = set(zh) - set(en)
        extra = set(en) - set(zh)
        raise SystemExit(f"key mismatch missing={missing} extra={extra}")
    write_arb(L10N / "app_zh.arb", zh)
    write_arb(L10N / "app_en.arb", en)


if __name__ == "__main__":
    main()
